export const ICON_NAMES = Object.keys(DESENHOS);

/**
 * <Icon name="trash" />  — 16px, traço 1,5px, currentColor.
 * `size` em px; `stroke` é a espessura do traço NA TELA (px), não em unidades do viewBox.
 */
export function Icon({ name, size = 16, stroke = 1.5, title, className, ...rest }) {
  const desenho = DESENHOS[name];
  if (!desenho) {
    avisarUmaVez("UI_ICONE_DESCONHECIDO", "ícone sem desenho; nada foi renderizado", {
      nome: name,
      disponiveis: ICON_NAMES,
    });
    return null;
  }
  const acessivel = title ? { role: "img", "aria-label": title } : { "aria-hidden": "true" };
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={(stroke * 24) / size}
      strokeLinecap="round"
      strokeLinejoin="round"
      focusable="false"
      className={className}
      style={{ flexShrink: 0 }}
      {...acessivel}
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {desenho}
    </svg>
  );
}
